<?php
// Script to generate SQL file offline
$sqlFile = 'new_tables.sql';
$handle = fopen($sqlFile, 'w');

function writeSQL($handle, $txt)
{
    fwrite($handle, $txt . "\n");
}

writeSQL($handle, "-- Database Schema for Cakes and Cards");
writeSQL($handle, "-- Generated by Agent");
writeSQL($handle, "");

// 1. Tables
$tables = [
    "CREATE TABLE IF NOT EXISTS `cakes` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `package_type` enum('luxury','regular','medium') NOT NULL,
  `name` varchar(255) NOT NULL,
  `description` text DEFAULT NULL,
  `image_url` varchar(255) DEFAULT NULL,
  `category` varchar(50) DEFAULT 'Cakes',
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;",

    "CREATE TABLE IF NOT EXISTS `user_cake_selections` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `user_id` int(11) NOT NULL,
  `cake_id` int(11) NOT NULL,
  `selected_at` timestamp NOT NULL DEFAULT current_timestamp(),
  PRIMARY KEY (`id`),
  KEY `user_id` (`user_id`),
  KEY `cake_id` (`cake_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;",

    "CREATE TABLE IF NOT EXISTS `invitation_cards` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `package_type` enum('luxury','regular','medium') NOT NULL,
  `name` varchar(255) NOT NULL,
  `image_url` varchar(255) DEFAULT NULL,
  PRIMARY KEY (`id`)
