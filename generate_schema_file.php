foreach ($tables as $t) {
    writeSQL($handle, $t);
    writeSQL($handle, "");
}

// 2. Data Extraction
function extractCakes($filePath, $packageType, $handle)
{
    if (!file_exists($filePath))
        return;
    $html = file_get_contents($filePath);
    $dom = new DOMDocument();
    @$dom->loadHTML($html);
    $xpath = new DOMXPath($dom);
    $sections = $xpath->query("//section[@class='menu-section']");
    foreach ($sections as $section) {
        $header = $xpath->query(".//h2", $section)->item(0);
        $category = 'Cakes';
        if ($header && stripos($header->nodeValue, 'Drink') !== false) {
            $category = 'Drinks';
        }
        $cards = $xpath->query(".//div[@class='dish-card']", $section);
        foreach ($cards as $card) {
            $nameNode = $xpath->query(".//h3", $card)->item(0);
            $descNode = $xpath->query(".//p", $card)->item(0);
            $imgNode = $xpath->query(".//img", $card)->item(0);
            $name = $nameNode ? trim($nameNode->nodeValue) : '';
            $description = $descNode ? trim($descNode->nodeValue) : '';
            $imgUrl = $imgNode ? $imgNode->getAttribute('src') : '';
            if ($name) {
                $sql = sprintf(
                    "INSERT INTO `cakes` (`package_type`, `name`, `description`, `image_url`, `category`) VALUES ('%s', '%s', '%s', '%s', '%s');",
                    $packageType,
                    addslashes($name),
                    addslashes($description),
                    addslashes($imgUrl),
                    addslashes($category)
                );
                writeSQL($handle, $sql);
            }
        }
    }
}

extractCakes('regCake.html', 'regular', $handle);
extractCakes('medCake.html', 'medium', $handle);
extractCakes('LuxCake.php', 'luxury', $handle);

function extractCards($filePath, $packageType, $handle)
{
    if (!file_exists($filePath))
        return;
    $html = file_get_contents($filePath);
    $dom = new DOMDocument();
    @$dom->loadHTML($html);
    $xpath = new DOMXPath($dom);
    $cards = $xpath->query("//div[contains(@class, 'card-option')]");
    foreach ($cards as $card) {
        $nameNode = $xpath->query(".//h3", $card)->item(0);
        $imgNode = $xpath->query(".//img", $card)->item(0);
        $name = $nameNode ? trim($nameNode->nodeValue) : 'Unknown Card';
        $imgUrl = $imgNode ? $imgNode->getAttribute('src') : '';
        if ($imgUrl) {
            $sql = sprintf(
                "INSERT INTO `invitation_cards` (`package_type`, `name`, `image_url`) VALUES ('%s', '%s', '%s');",
                $packageType,
                addslashes($name),
                addslashes($imgUrl)
            );
            writeSQL($handle, $sql);
        }
    }
}

extractCards('invCardLux.html', 'luxury', $handle);
extractCards('invCardMed.html', 'medium', $handle);
extractCards('invCardReg.html', 'regular', $handle);

fclose($handle);
echo "SQL file generated: $sqlFile";
?>